const getSourceName = (sourcePath: string) => sourcePath.split(/[\\/]/).pop()?.replace(/\.(tsx|ts)$/, '') || sourcePath;

export const SANDBOX_EVENT_GROUPS: SandboxEventGroup[] = Array.from(
  SANDBOX_EVENTS.reduce((groups, event) => {
    const sourcePath = event.sourcePath || event.id;
    groups.set(sourcePath, [...(groups.get(sourcePath) || []), event]);
    return groups;
  }, new Map<string, SandboxGameEvent[]>()),
).map(([sourcePath, events]) => {
  const sourceName = getSourceName(sourcePath);
  const incoming = incomingWithinSource.get(sourcePath) || new Set<string>();
  const sorted = [...events].sort((a, b) => (a.sourceOrder || 0) - (b.sourceOrder || 0) || a.id.localeCompare(b.id));
  const root =
    sorted.find((event) => event.id === sourceName) ||
    sorted.find((event) => event.id === `${sourceName}_1`) ||
    sorted.find((event) => !incoming.has(event.id)) ||
    sorted[0];
  return {
    id: sourcePath,
    sourcePath,
    sourceName,
    rootEventId: root.id,
    eventIds: sorted.map((event) => event.id),
    title: typeof root.title === 'string' ? root.title : root.id,
    titleZh: typeof root.titleZh === 'string' ? root.titleZh : undefined,
  };
}).sort((a, b) => a.sourcePath.localeCompare(b.sourcePath));

