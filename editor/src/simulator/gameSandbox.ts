const shouldSkipDiffPath = (path: string) =>
  /(^|\.)(hand|discard|actionDeck|governmentDeck|militaryDeck|advisorPool|activeAdvisors|pendingEvents|currentEvent)(\.|$)/.test(path);

const collectDiffs = (before: unknown, after: unknown, path = '', diffs: SandboxDiff[] = [], depth = 0): SandboxDiff[] => {
  if (diffs.length >= 90 || shouldSkipDiffPath(path)) return diffs;
  if (before === after) return diffs;
  if (typeof before === 'function' || typeof after === 'function') return diffs;
  const beforeIsObject = before !== null && typeof before === 'object';
  const afterIsObject = after !== null && typeof after === 'object';
  if (!beforeIsObject || !afterIsObject || depth >= 4 || Array.isArray(before) || Array.isArray(after)) {
    diffs.push({ path: path || 'state', before: stringifyValue(before), after: stringifyValue(after) });
    return diffs;
  }
  const keys = new Set([...Object.keys(before as Record<string, unknown>), ...Object.keys(after as Record<string, unknown>)]);
  keys.forEach((key) => {
    collectDiffs(
      (before as Record<string, unknown>)[key],
      (after as Record<string, unknown>)[key],
      path ? `${path}.${key}` : key,
      diffs,
      depth + 1,
    );
  });
  return diffs;
};

const eventSummary = (state: GameState, language: 'en' | 'zh') => ({
  currentEventId: state.currentEvent?.id,
  currentEventTitle: state.currentEvent ? getSandboxEventTitle(state.currentEvent, state, language) : undefined,
  pendingEventIds: (state.pendingEvents || []).map((event) => event.id),
});

const makeRun = (
  before: GameState,
  after: GameState,
  partial: Partial<GameState> | undefined,
  targetType: SandboxTargetType,
  targetId: string,
  targetTitle: string,
  language: 'en' | 'zh',
  logs: string[],
  optionIndex?: number,
  optionTitle?: string,
  optionSubtitle?: string,
): SandboxRun => ({
  ok: true,
  targetType,
  targetId,
  targetTitle,
  optionIndex,
  optionTitle,
  optionSubtitle,
  before,
  after,
  partial,
  diffs: collectDiffs(before, after),
  ...eventSummary(after, language),
  logs,
});

const blockedRun = (
  state: GameState,
  targetType: SandboxTargetType,
  targetId: string,
  targetTitle: string,
  blockedReason: string,
): SandboxRun => ({
  ok: false,
  blockedReason,
  targetType,
  targetId,
  targetTitle,
  before: state,
  after: state,
  diffs: [],
  pendingEventIds: [],
  logs: [blockedReason],
});

export const resolveSandboxEventOption = (
  before: GameState,
  event: GameEvent,
  optionIndex: number,
  options: Pick<SandboxRunOptions, 'force'>,
  language: 'en' | 'zh',
): SandboxRun => {
  const targetTitle = getSandboxEventTitle(event, before, language);
  try {
    if (!options.force && event.condition && !event.condition(before)) {
      return blockedRun(before, 'event', event.id, targetTitle, 'Event condition is not satisfied.');
    }
    const option = event.options[optionIndex] || event.options[0];
    if (!option) return blockedRun(before, 'event', event.id, targetTitle, 'Event has no options.');
    const optionTitle = resolveText(language === 'zh' ? option.textZh : option.text, before, `Option ${optionIndex + 1}`);
    const optionSubtitle = resolveText(language === 'zh' ? option.subtitleZh || option.subtitle : option.subtitle, before);
    if (!options.force && option.condition && !option.condition(before)) {
      return blockedRun(before, 'event', event.id, targetTitle, 'Option condition is not satisfied.');
    }
    const partial = normalizeSandboxTransition(option.effect(before));
    const after = {
      ...before,
      ...partial,
      currentEvent: partial.currentEvent || null,
    };
    if (!after.currentEvent && after.pendingEvents.length === 0 && after.phase === 'event') {
      after.phase = 'action';
      after.actionsLeft = 2;
    }
    return makeRun(before, after, partial, 'event', event.id, targetTitle, language, ['Event option resolved.'], optionIndex, optionTitle, optionSubtitle);
  } catch (error) {
    return blockedRun(before, 'event', event.id, targetTitle, error instanceof Error ? error.message : 'Event simulation failed.');
  }
};

export const playSandboxCard = (
  before: GameState,
  card: Card,
  options: Pick<SandboxRunOptions, 'force' | 'unlimitedActions'>,
  language: 'en' | 'zh',
): SandboxRun => {
  const targetTitle = getSandboxCardTitle(card, language);
  try {
    if (!options.force && !options.unlimitedActions && before.actionsLeft <= 0) return blockedRun(before, 'card', card.id, targetTitle, 'No action points left.');
    if (!options.force && card.resourceCost !== undefined && before.resources < card.resourceCost) {
      return blockedRun(before, 'card', card.id, targetTitle, 'Insufficient resources.');
    }
    if (!options.force && card.armamentCost !== undefined && before.armaments < card.armamentCost) {
      return blockedRun(before, 'card', card.id, targetTitle, 'Insufficient armaments.');
    }
    if (!options.force && card.condition && !card.condition(before)) {
      return blockedRun(before, 'card', card.id, targetTitle, 'Card condition is not satisfied.');
    }
    const partial = card.effect(before);
    const after = {
      ...before,
      ...partial,
      actionsLeft: options.unlimitedActions ? before.actionsLeft : before.actionsLeft - card.cost,
      resources: before.resources - (card.resourceCost || 0),
      armaments: before.armaments - (card.armamentCost || 0),
      hand: before.hand.filter((item) => item.id !== card.id),
      discard: [...before.discard, card],
    };
    return makeRun(before, after, partial, 'card', card.id, targetTitle, language, ['Card played with game cost rules.']);
  } catch (error) {
    return blockedRun(before, 'card', card.id, targetTitle, error instanceof Error ? error.message : 'Card simulation failed.');
  }
};

export const playSandboxHandCard = (
  before: GameState,
  handIndex: number,
  options: Pick<SandboxRunOptions, 'force' | 'unlimitedActions'>,
  language: 'en' | 'zh',
): SandboxRun => {
  const card = before.hand[handIndex];
  if (!card) return blockedRun(before, 'card', `hand_${handIndex}`, `Hand ${handIndex + 1}`, 'No card in this hand slot.');
  const run = playSandboxCard(before, card, options, language);
  if (!run.ok) return run;
  return {
    ...run,
    after: {
      ...run.after,
      hand: before.hand.filter((_, index) => index !== handIndex),
      discard: [...before.discard, card],
    },
  };
};

export const resolveSandboxAdvisorAction = (
  before: GameState,
  advisor: Advisor,
  actionIndex: number,
  options: Pick<SandboxRunOptions, 'force' | 'unlimitedActions'>,
  language: 'en' | 'zh',
): SandboxRun => {
  const targetTitle = getSandboxAdvisorTitle(advisor, language);
  const action = advisor.actions[actionIndex] || advisor.actions[0];
  if (!action) return blockedRun(before, 'advisor', advisor.id, targetTitle, 'Advisor has no actions.');
  try {
    if (!options.force && !options.unlimitedActions && before.actionsLeft <= 0) return blockedRun(before, 'advisor', advisor.id, targetTitle, 'No action points left.');
    if (!options.force && !action.condition(before)) {
      return blockedRun(before, 'advisor', advisor.id, targetTitle, 'Advisor action condition is not satisfied.');
    }
    const partial = action.effect(before);
    const after = {
      ...before,
      ...partial,
      actionsLeft: options.unlimitedActions ? before.actionsLeft : before.actionsLeft - 1,
    };
    return makeRun(
      before,
      after,
      partial,
      'advisor',
      advisor.id,
      targetTitle,
      language,
      ['Advisor action resolved with one action point cost.'],
      actionIndex,
      getSandboxActionTitle(action, language),
      language === 'zh' ? action.subtitleZh || action.subtitle : action.subtitle,
    );
  } catch (error) {
    return blockedRun(before, 'advisor', advisor.id, targetTitle, error instanceof Error ? error.message : 'Advisor simulation failed.');
  }
};

export const resolveSandboxAdvisorSlotAction = (
  before: GameState,
  slotIndex: number,
  actionIndex: number,
  options: Pick<SandboxRunOptions, 'force' | 'unlimitedActions'>,
  language: 'en' | 'zh',
): SandboxRun => {
  const advisor = before.activeAdvisors[slotIndex];
  if (!advisor) return blockedRun(before, 'advisor', `slot_${slotIndex}`, `Slot ${slotIndex + 1}`, 'No advisor in this slot.');
  return resolveSandboxAdvisorAction(before, advisor, actionIndex, options, language);
};
