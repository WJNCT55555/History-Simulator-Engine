const getSandboxTriggerMode = (difficulty: SandboxDifficulty): EventTriggerMode =>
  difficulty === 'historical' ? 'historical' : 'nonHistorical';

export const testSandboxEventTrigger = (
  eventId: string,
  scenario: SandboxScenario,
  difficulty: SandboxDifficulty,
  targetDate?: { year: number; month: number },
): SandboxTriggerResult => {
  const state = createSandboxState(scenario, difficulty);
  const event = runtimeEventsById.get(eventId) || sandboxEventById.get(eventId);
  const date = targetDate || { year: state.year, month: state.month };
  const mode = getSandboxTriggerMode(difficulty);
  if (!event) {
    return {
      eligible: false,
      eventId,
      mode,
      targetDate: date,
      reason: 'Event not found in the runtime registry.',
      reasonZh: '运行时事件注册表中找不到该事件。',
    };
  }

  try {
    const eligible = shouldQueueEvent(event, state, {
      mode,
      date,
      pendingEvents: [],
      currentEvent: null,
      respectHistory: false,
    });
    if (eligible) {
      return {
        eligible: true,
        eventId,
        mode,
        targetDate: date,
        reason: 'Event is eligible for the ordinary queue in this mode and month.',
        reasonZh: '该事件符合当前模式和月份的普通事件队列条件。',
      };
    }

    if (mode === 'historical' && event.date && (event.date.year !== date.year || event.date.month !== date.month)) {
      return {
        eligible: false,
        eventId,
        mode,
        targetDate: date,
        reason: `Historical date mismatch: event is dated ${event.date.year}-${String(event.date.month).padStart(2, '0')}.`,
        reasonZh: `历史日期不匹配：事件日期为 ${event.date.year} 年 ${event.date.month} 月。`,
      };
    }
    if (mode === 'nonHistorical' && !event.condition) {
      return {
        eligible: false,
        eventId,
        mode,
        targetDate: date,
        reason: 'Non-historical modes require a true condition; date alone is ignored.',
        reasonZh: '非历史模式需要事件 condition 为真；单独的 date 不会触发事件。',
      };
    }
    return {
      eligible: false,
      eventId,
      mode,
      targetDate: date,
      reason: 'Event condition is false for the current scenario and test state.',
      reasonZh: '在当前剧本和测试状态下，事件 condition 不满足。',
    };
  } catch (error) {
    return {
      eligible: false,
      eventId,
      mode,
      targetDate: date,
      reason: error instanceof Error ? `Event condition threw: ${error.message}` : 'Event condition threw an error.',
      reasonZh: error instanceof Error ? `事件 condition 执行出错：${error.message}` : '事件 condition 执行出错。',
    };
  }
};

