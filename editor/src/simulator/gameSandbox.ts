const stringifyValue = (value: unknown): string => {
  if (typeof value === 'function') return '[function]';
  if (value === undefined) return 'undefined';
  if (value === null) return 'null';
  if (typeof value === 'string') return value;
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return `[${value.length} items]`;
  if (typeof value === 'object') {
    const maybeId = value as { id?: unknown; title?: unknown; name?: unknown };
    if (typeof maybeId.id === 'string') return maybeId.id;
    if (typeof maybeId.title === 'string') return maybeId.title;
    if (typeof maybeId.name === 'string') return maybeId.name;
    return '{...}';
  }
  return String(value);
};

const cloneValue = <T>(value: T, seen = new WeakMap<object, unknown>()): T => {
  if (value === null || typeof value !== 'object') return value;
  if (typeof value === 'function') return value;
  const objectValue = value as object;
  const existing = seen.get(objectValue);
  if (existing) return existing as T;
  if (Array.isArray(value)) {
    const clone: unknown[] = [];
    seen.set(objectValue, clone);
    value.forEach((item) => clone.push(cloneValue(item, seen)));
    return clone as T;
  }
  const clone: Record<string, unknown> = {};
  seen.set(objectValue, clone);
  Object.entries(value as Record<string, unknown>).forEach(([key, entry]) => {
    clone[key] = cloneValue(entry, seen);
  });
  return clone as T;
};

const resolveText = (value: string | ((state: GameState) => string) | undefined, state: GameState, fallback = '') => {
  try {
    if (typeof value === 'function') return value(state);
    return value || fallback;
  } catch {
    return fallback;
  }
};

